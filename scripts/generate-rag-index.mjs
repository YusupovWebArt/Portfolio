import fs from 'node:fs'
import path from 'node:path'
import { createServer } from 'vite'

const ROOT_DIR = process.cwd()
const JSON_OUTPUT_PATH = path.resolve(ROOT_DIR, 'src/lib/ai/generated/rag-index.generated.json')
const TS_OUTPUT_PATH = path.resolve(ROOT_DIR, 'src/lib/ai/generated/rag-index.generated.ts')

async function main() {
  const startedAt = performance.now()
  const server = await createServer({
    root: ROOT_DIR,
    logLevel: 'error',
    server: { middlewareMode: true, hmr: false },
    appType: 'custom',
    optimizeDeps: { noDiscovery: true },
  })

  try {
    const mod = await server.ssrLoadModule('/src/lib/ai/knowledge-builder.ts')
    if (typeof mod.buildPrebuiltKnowledgeData !== 'function') {
      throw new Error('buildPrebuiltKnowledgeData export not found in src/lib/ai/knowledge-builder.ts')
    }

    const data = mod.buildPrebuiltKnowledgeData()
    fs.mkdirSync(path.dirname(TS_OUTPUT_PATH), { recursive: true })
    const serialized = JSON.stringify(data)

    // Emit compact JS string wrapper so bundlers (esbuild/Rolldown) do not pretty-print
    // flat numeric posting arrays and V8 parses via its native C++ JSON.parse fast path.
    const tsModule =
      '// Auto-generated by scripts/generate-rag-index.mjs. Do not edit manually.\n' +
      'import type { PrebuiltKnowledgeData } from \'../knowledge-types\'\n\n' +
      `const RAW_RAG_INDEX_JSON = ${JSON.stringify(serialized)}\n\n` +
      'export const PREBUILT_RAG_DATA: PrebuiltKnowledgeData = JSON.parse(RAW_RAG_INDEX_JSON) as PrebuiltKnowledgeData\n'

    fs.writeFileSync(TS_OUTPUT_PATH, tsModule, 'utf8')
    if (fs.existsSync(JSON_OUTPUT_PATH)) {
      fs.rmSync(JSON_OUTPUT_PATH, { force: true })
    }

    const sizeKb = (Buffer.byteLength(serialized, 'utf8') / 1024).toFixed(1)
    const elapsedMs = (performance.now() - startedAt).toFixed(0)
    const uniqueTokens = Object.keys(data.bm25.postings).length

    console.log(
      `[OK] Generated src/lib/ai/generated/rag-index.generated.ts (${sizeKb} KB payload, ${data.counts.totalChunks} chunks, ${uniqueTokens} indexed tokens, ${data.blogSummaries.length} blog summaries) in ${elapsedMs}ms`,
    )
  } finally {
    await server.close()
  }
}

main().catch((err) => {
  console.error('[ERROR] Failed to generate prebuilt RAG index:', err)
  process.exit(1)
})
